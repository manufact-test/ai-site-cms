'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const R=require('../sdk/recipes.cjs'),D=require('../sdk/draft.cjs');
const manifests=fs.readdirSync(path.join(__dirname,'../components')).map(f=>JSON.parse(fs.readFileSync(path.join(__dirname,'../components',f),'utf8')));
const input={siteId:'site-recipe-test',title:'Компания из задания',task:'Нужен сайт услуг',facts:{headline:'Подтверждённый заголовок',description:'Текст от владельца',offerings:['Первая услуга','Вторая услуга','Третья услуга'],details:['Факт от владельца']}};
const recipe=R.plan(input),result=R.compose(recipe,manifests);
assert.equal(result.mode,'deterministic');assert.equal(result.site.pages.length,4);
assert.equal(JSON.stringify(result),JSON.stringify(R.compose(JSON.parse(JSON.stringify(recipe)),manifests)));
assert.match(JSON.stringify(result.site),/Третья услуга/);assert.match(JSON.stringify(result.site),/Факт от владельца/);
assert.doesNotMatch(JSON.stringify(result.site),/Оборудование для вашего производства/);
const source=result.site,template={id:'template-123456789012345678',component:'company-hero',section:structuredClone(source.pages[0].sections[0])};
template.section.elements[0].values['content.text']='Сохранённый заголовок владельца';
const reuse=structuredClone(recipe);reuse.sourceSiteId=source.siteId;reuse.pages[0].sections[0].templateId=template.id;
const composed=R.compose(reuse,manifests,{sourceSite:source,templates:[template]});
assert.equal(composed.site.pages[0].sections[0].elements[0].values['content.text'],'Сохранённый заголовок владельца');
const themed=structuredClone(source);
themed.theme={background:'#1b2233',surface:'#ffffff',text:'#f0f0f0',primary:'#ee7700',font:'arial',maxWidth:940};
themed.pages[0].seo={title:'Подтверждённое SEO',description:'Описание страницы',robots:'noindex'};
themed.pages[0].navigation={label:'Главная компании',hidden:false};
const preserved=R.compose(reuse,manifests,{sourceSite:themed,templates:[template]}).site;
assert.deepEqual(preserved.theme,themed.theme,'Owner palette survives same-site regeneration');
assert.deepEqual(preserved.pages[0].seo,themed.pages[0].seo,'Owner SEO survives same-path regeneration');
assert.deepEqual(preserved.pages[0].navigation,themed.pages[0].navigation,'Owner menu survives same-path regeneration');

let session=D.begin(source,manifests);session=D.replaceSite(session,manifests,composed.site,0);
assert.deepEqual(D.undo(session,manifests).current,source);
assert.throws(()=>R.compose(reuse,manifests,{sourceSite:{...source,siteId:'site-other'},templates:[template]}));
assert.throws(()=>R.compose({...recipe,execute:'script'},manifests));
const unsafe=structuredClone(recipe);unsafe.pages[0].sections[0].component='unregistered-code';assert.throws(()=>R.compose(unsafe,manifests));
const invalid=structuredClone(recipe);invalid.facts.contactUrl='javascript:alert(1)';assert.throws(()=>R.compose(invalid,manifests));
const duplicate=structuredClone(recipe);duplicate.pages[1].path='/';assert.throws(()=>R.compose(duplicate,manifests));
for(const preset of Object.keys(R.PRESETS))assert.ok(R.compose(R.plan({...input,preset}),manifests).site.pages.length);
console.log('STAGE3 SITE RECIPES PASS: deterministic composition, facts, safe registry, links, same-site templates and Undo');
