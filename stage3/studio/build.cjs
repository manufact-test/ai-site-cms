'use strict';
// Hermetic Stage3 browser bundle: inlines only first-party pinned SDK,
// registered JSON manifests, fixture and static editor controller.
// No npm, network, dynamic imports or arbitrary script eval.
const fs=require('node:fs'),path=require('node:path');
const here=__dirname,root=path.resolve(here,'..');
const design=fs.readFileSync(path.join(root,'sdk/design-graph.cjs'),'utf8');
const contract=fs.readFileSync(path.join(root,'sdk/contract.cjs'),'utf8');
const draft=fs.readFileSync(path.join(root,'sdk/draft.cjs'),'utf8');
const recipes=fs.readFileSync(path.join(root,'sdk/recipes.cjs'),'utf8');
const composer=fs.readFileSync(path.join(here,'composer.js'),'utf8');
const app=fs.readFileSync(path.join(here,'app.js'),'utf8');
const manifests=['company-hero','feature-highlights','contact-panel','image-showcase','lead-form','lead-form-flex','service-grid','faq-accordion','testimonials','photo-gallery','media-story','partner-logos','cta-banner','pricing-plans','process-timeline','comparison-matrix','content-switcher','adaptive-gallery'].map(
  id=>JSON.parse(fs.readFileSync(path.join(root,'components',id+'.json'),'utf8')));
const fixture=JSON.parse(fs.readFileSync(path.join(root,'fixtures/industrial-site.json'),'utf8'));
const compiled="// GENERATED by stage3/studio/build.cjs — DO NOT EDIT MANUALLY.\n"+
  "(()=>{'use strict';\n"+
  "const DESIGN_GRAPH=(()=>{const module={exports:{}};\n"+design+"\nreturn module.exports;})();\n"+
  "const CONTRACT=(()=>{const module={exports:{}};const require=name=>{if(name==='./design-graph.cjs')return DESIGN_GRAPH;throw Error('Unknown contract import');};\n"+contract+"\nreturn module.exports;})();\n"+
  "const DRAFT=(()=>{const module={exports:{}};const require=name=>{if(name==='./contract.cjs')return CONTRACT;throw Error('Unknown SDK import');};\n"+
  draft+"\nreturn module.exports;})();\n"+
  "const RECIPES=(()=>{const module={exports:{}};const require=name=>{if(name==='./contract.cjs')return CONTRACT;throw Error('Unknown recipe import');};\n"+recipes+"\nreturn module.exports;})();\n"+
  "const MANIFESTS="+JSON.stringify(manifests)+";\n"+
  "const FIXTURE="+JSON.stringify(fixture)+";\n"+
  app+"\n"+composer+"\n})();\n";
const destination=path.join(here,'bundle.js');
if(process.argv[2]==='--check'){
  if(!fs.existsSync(destination)||fs.readFileSync(destination,'utf8')!==compiled){
    throw Error('Browser bundle does not match typed SDK / manifest sources. Run node stage3/studio/build.cjs');
  }
  console.log('Stage3 first-party browser bundle parity PASS');
}else{
  fs.writeFileSync(destination,compiled,'utf8');
  console.log('Offline Stage3 browser Studio bundle: '+Buffer.byteLength(compiled)+' bytes');
}
