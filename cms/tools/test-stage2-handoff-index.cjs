'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');
const {spawnSync}=require('node:child_process');
const crypto=require('node:crypto');
const {OUT}=require('./stage2-license-dossier.cjs');
const legal=require('./stage2-license-dossier.cjs');
const owner=require('./stage2-owner-decision.cjs');
const handoff=require('./stage2-handoff-index.cjs');
let checks=0;
const ok=(condition,msg)=>{assert.ok(condition,msg);checks++;};
const denied=(fn,msg)=>{assert.throws(fn,undefined,msg);checks++;};
const digest=bytes=>crypto.createHash('sha256').update(bytes).digest('hex');
const script=path.join(__dirname,'stage2-handoff-index.cjs');
const cli=(args)=>spawnSync(process.execPath,[script,...args],{encoding:'utf8'});
function main(){
 legal.build();owner.build();
 const index=handoff.build();
 const required=['stage2-license-dossier.json','stage2-license-dossier.html',
  'stage2-owner-decision.json','stage2-owner-decision.html',
  handoff.WORKSHEET,handoff.ACTIONS,handoff.ACTIONS_PAGE];
 ok(Object.keys(index.files).sort().join('|')===required.sort().join('|'),
  'offline owner receipt covers every needed clean legal and decision file');
 ok(index.stage2Accepted===false&&index.stage3Authorized===false&&
   index.untrustedUnsignedIndex===true&&index.noHostAccessPerformed===true,
  'handoff explicitly denies acceptance, provenance signature and host access');
 const srcFiles=[...required,handoff.INDEX,handoff.PAGE];
 for(const name of srcFiles) {
  const f=fs.statSync(path.join(OUT,name));
  ok(f.size>100&&(f.mode&0o077)===0,
    'each uploaded owner file is private and nonempty: '+name);
 }
 const original={};
 for(const name of srcFiles)original[name]=fs.readFileSync(path.join(OUT,name));
 const report=JSON.parse(original[handoff.INDEX]);
 ok(report.packageManifestSha256===
   JSON.parse(original['stage2-owner-decision.json']).packageManifestSha256,
   'source legal/owner packet and handoff describe identical verified release');
 ok(JSON.stringify(report).includes('"sourceCommitSha":')&&
   report.lockedComponents===43&&report.gateCount===8,
   'source commit, 43 dependencies and eight manual gates indexed');
 ok(original[handoff.PAGE].toString('utf8').includes('Stage 3 NOT AUTHORIZED')
   &&original[handoff.WORKSHEET].toString('utf8').includes('NOT ACCEPTED')
   &&!original[handoff.PAGE].toString('utf8').includes('<script')
   &&original[handoff.ACTIONS].toString('utf8').includes('УСКОРЕННЫЙ РЕЖИМ')
   &&original[handoff.ACTIONS_PAGE].toString('utf8').includes('issues/9'),
   'offline no-script owner explanation preserves negative approval semantics');
 const noArg=cli([]);
 ok(noArg.status===3&&noArg.stdout===''&&noArg.stderr.trim()==='STAGE2_HANDOFF_REFUSED',
   'CLI must not run implicitly');
 const permitted=cli(['--verify']);
 ok(permitted.status===0&&permitted.stderr==='',
   'real CLI --verify accepts coherent staged handoff');
 const same=cli(['--build']);
 ok(same.status===0&&srcFiles.every(f=>fs.readFileSync(path.join(OUT,f)).equals(original[f])),
   'offline handoff build is reproducible byte-for-byte on same checkout');
 function corrupt(name,make,reason){
  const file=path.join(OUT,name);
  try{
   make(file,original[name]);
   denied(()=>handoff.verify(),reason);
   const test=cli(['--verify']);
   ok(test.status===3&&test.stdout===''&&test.stderr.trim()==='STAGE2_HANDOFF_REFUSED',
    reason+' through real CLI');
  }finally{
   fs.rmSync(file,{force:true});
   fs.writeFileSync(file,original[name],{mode:0o600});
  }
 }
 corrupt('stage2-owner-decision.json',f=>{
  const report=JSON.parse(original['stage2-owner-decision.json']);
  report.stage2Accepted=true;
  fs.writeFileSync(f,JSON.stringify(report));
 },'unsigned owner approval cannot be forged');
 corrupt('stage2-license-dossier.json',f=>{
  const report=JSON.parse(original['stage2-license-dossier.json']);
  report.independentLegalApproval=true;
  fs.writeFileSync(f,JSON.stringify(report));
 },'human legal signature cannot be autogenerated');
 corrupt(handoff.INDEX,f=>{
  const changed=JSON.parse(original[handoff.INDEX]);
  changed.stage2Accepted=true;
  fs.writeFileSync(f,JSON.stringify(changed));
 },'index itself cannot claim acceptance');
 corrupt(handoff.INDEX,f=>{
  const changed=JSON.parse(original[handoff.INDEX]);
  changed.files['stage2-owner-decision.json'].sha256='0'.repeat(64);
  fs.writeFileSync(f,JSON.stringify(changed));
 },'hash list cannot be changed without detection');
 corrupt(handoff.ACTIONS,f=>fs.appendFileSync(f,'Hostinger granted\n'),
  'unsafe changes to human gate plan rejected');
 corrupt(handoff.ACTIONS_PAGE,f=>fs.appendFileSync(f,'<script>alert(1)</script>'),
  'standalone owner actions page is immutable');
 corrupt(handoff.WORKSHEET,f=>fs.appendFileSync(f,'Approval: granted\n'),
  'human review worksheet cannot be silently marked approved');
 corrupt(handoff.PAGE,f=>fs.appendFileSync(f,'<script>alert(1)</script>'),
  'standalone offline overview cannot have extra active content injected');
 corrupt('stage2-owner-decision.html',f=>fs.appendFileSync(f,'altered'),
  'HTML review cannot differ from reviewed owner report');
 corrupt('stage2-license-dossier.html',f=>fs.appendFileSync(f,'altered'),
  'HTML license review cannot differ from audited license source');
 corrupt(handoff.PAGE,f=>{
  fs.rmSync(f);
  fs.symlinkSync(path.join(OUT,'stage2-owner-decision.html'),f);
 },'symlink substitution rejected');
 const indexFile=path.join(OUT,handoff.INDEX);
 try{
  fs.chmodSync(indexFile,0o644);
  denied(()=>handoff.verify(),'world-readable handoff index refused');
 }finally{fs.chmodSync(indexFile,0o600);}
 ok(handoff.verify(),'clean verifiable handoff recovered after all hostile inputs');
 ok(srcFiles.every(f=>digest(fs.readFileSync(path.join(OUT,f)))===digest(original[f])),
   'CI artifact restored exactly; no synthetic or malicious content persists');
 console.log('Stage2 package/legal/owner final offline transfer: '+checks+
   ' assertions PASS; 9 review attachments verified; unsigned, no host or Stage3 permission');
}
main();
