'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),os=require('node:os'),crypto=require('node:crypto');
const {STAGE,verify}=require('./build-internal-package.cjs');
const {LabRollout}=require('./lab-versioned-rollout.cjs');
let count=0;
function ok(cond,label){assert.ok(cond,label);count++;}
function denied(fn,pattern,label){assert.throws(fn,pattern,label);count++;}
const lab=new LabRollout();
const source=fs.mkdtempSync(path.join(os.tmpdir(),'ai-site-old-release-'));
try{
  ok(verify(STAGE).releaseVersion==='0.2.0-stage2.1','Pinned candidate release');
  fs.cpSync(STAGE,source,{recursive:true});
  const oldManifest=path.join(source,'private/package-manifest.json');
  const altered=JSON.parse(fs.readFileSync(oldManifest,'utf8'));
  altered.releaseVersion='0.2.0-stage2.0';
  const sbomFile=path.join(source,'private/compliance/sbom.cdx.json');
  const oldSbom=JSON.parse(fs.readFileSync(sbomFile,'utf8'));
  oldSbom.metadata.component.version='0.2.0-stage2.0';
  fs.writeFileSync(sbomFile,JSON.stringify(oldSbom,null,2)+'\n');
  const sbomBytes=fs.readFileSync(sbomFile);
  const sbomEntry=altered.files.find(f=>f.path==='private/compliance/sbom.cdx.json');
  sbomEntry.bytes=sbomBytes.length;
  sbomEntry.sha256=crypto.createHash('sha256').update(sbomBytes).digest('hex');
  fs.writeFileSync(oldManifest,JSON.stringify(altered,null,2)+'\n');
  ok(verify(source).releaseVersion==='0.2.0-stage2.0','Synthetic old lab slot');
  ok(lab.stage(source)==='0.2.0-stage2.0','Stage isolated old version');
  ok(lab.switchTo('0.2.0-stage2.0',null).current==='0.2.0-stage2.0','Activate baseline');
  ok(lab.stage(STAGE)==='0.2.0-stage2.1','Stage isolated upgrade');
  denied(()=>lab.stage(STAGE),/overwrite/,'Immutability prohibits staging same version');
  denied(()=>lab.switchTo('0.2.0-stage2.1',null),/Stale/,'Stale expected version fails');
  denied(()=>lab.switchTo('../etc/passwd','0.2.0-stage2.0'),/version/,'Version traversal denied');
  denied(()=>lab.switchTo('0.2.0-stage2.1','0.2.0-stage2.0','before-pointer'),/BEFORE/,'Pre-cutover fault injected');
  ok(lab.state().current==='0.2.0-stage2.0','Failed pre-cutover preserved working slot');
  denied(()=>lab.switchTo('0.2.0-stage2.1','0.2.0-stage2.0','after-pointer'),/AFTER/,'Post-cutover fault injected');
  ok(lab.state().current==='0.2.0-stage2.1','Post-cutover pointer state visible');
  ok(lab.rollback('0.2.0-stage2.1').current==='0.2.0-stage2.0','Verified explicit rollback succeeds');
  ok(lab.state().sequence===3,'Monotonic pointer sequence');
  ok(lab.switchTo('0.2.0-stage2.1','0.2.0-stage2.0').current==='0.2.0-stage2.1','Normal upgrade');
  const oldFile=path.join(lab.slot('0.2.0-stage2.0'),'private/editor/meta.json'),oldBytes=fs.readFileSync(oldFile);
  fs.appendFileSync(oldFile,'tamper');
  denied(()=>lab.rollback('0.2.0-stage2.1'),/mismatch/,'Rollback refuses corrupt target');
  ok(lab.state().current==='0.2.0-stage2.1','Corrupt rollback target did not change active');
  fs.writeFileSync(oldFile,oldBytes);
  ok(lab.rollback('0.2.0-stage2.1').current==='0.2.0-stage2.0','Rollback after source repair');
  const activeFile=path.join(lab.slot('0.2.0-stage2.1'),'public','unlisted.php');
  fs.writeFileSync(activeFile,'<?php echo 1;');
  denied(()=>lab.switchTo('0.2.0-stage2.1','0.2.0-stage2.0'),/Unlisted/,'Injected payload prevents activation');
  fs.unlinkSync(activeFile);
  const pointer=lab.pointerPath(),valid=fs.readFileSync(pointer);
  fs.writeFileSync(pointer,'{"current":"../../site","previous":null,"sequence":9}');
  denied(()=>lab.state(),/version/,'Injected activation path refused');
  fs.writeFileSync(pointer,valid);
  ok(lab.state().current==='0.2.0-stage2.0','Unmodified pointer recovered');
  denied(()=>lab.rollback('0.2.0-stage2.1'),/matching/,'Stale rollback refused');
  ok(!fs.existsSync(path.join(STAGE,'active.json')),'Builder source never mutated');
  ok(!fs.existsSync(path.join(lab.root,'public')),'Lab switch is metadata ONLY, not a production HTTP pointer');
  console.log('Stage2 disposable versioned rollout/rollback PASS: '+count+' assertions; no real site or DB');
}finally{lab.dispose();fs.rmSync(source,{recursive:true,force:true})}
